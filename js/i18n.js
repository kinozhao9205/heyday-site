  var STORAGE_KEY = 'heyday-lang';
  var LANGS = ['en', 'zh', 'uz'];
  var currentLang = 'en';

  // Expose a read-only accessor for other scripts (e.g. case-card toggles)
  window.HEYDAY_I18N = {
    text: function (key) {
      return (I18N[currentLang] && I18N[currentLang].hasOwnProperty(key)) ? I18N[currentLang][key] : null;
    }
  };

  function detectLang() {
    try {
      var saved = localStorage.getItem(STORAGE_KEY);
      if (LANGS.indexOf(saved) !== -1) return saved;
    } catch (e) { /* localStorage unavailable */ }
    return 'en'; // default language is English
  }

  function langAttr(lang) {
    if (lang === 'zh') return 'zh-Hant';
    if (lang === 'uz') return 'uz';
    return 'en';
  }

  function applyLang(lang, animate) {
    currentLang = lang;
    var dict = I18N[lang];

    var nodes = document.querySelectorAll('[data-i18n]');
    for (var i = 0; i < nodes.length; i++) {
      var el = nodes[i];
      var key = el.getAttribute('data-i18n');
      if (!key || !dict.hasOwnProperty(key)) continue;
      if (el.textContent === dict[key]) continue;
      if (animate && typeof gsap !== 'undefined') {
        (function (node, text) {
          gsap.to(node, {
            opacity: 0, y: -6, duration: 0.18, ease: 'power2.in',
            onComplete: function () {
              node.textContent = text;
              gsap.to(node, { opacity: 1, y: 0, duration: 0.28, ease: 'power2.out' });
            }
          });
        })(el, dict[key]);
      } else {
        el.textContent = dict[key];
      }
    }


    // Re-sync expand toggle labels for open case cards
    // (delayed so the gsap text-swap animation above doesn't overwrite it)
    setTimeout(function () {
      var openBtns = document.querySelectorAll('.case-card.open .case-toggle [data-i18n="cs_more"]');
      for (var ob = 0; ob < openBtns.length; ob++) {
        openBtns[ob].textContent = dict.cs_less;
      }
    }, animate ? 650 : 0);
    document.documentElement.lang = langAttr(lang);
    document.title = dict._title;
    var meta = document.querySelector('meta[name="description"]');
    if (meta) meta.setAttribute('content', dict._desc);

    // Switcher state
    var switcher = document.getElementById('lang-switcher');
    if (switcher) {
      for (var l = 0; l < LANGS.length; l++) {
        switcher.classList.toggle('lang-' + LANGS[l], lang === LANGS[l]);
      }
    }
    var btns = document.querySelectorAll('[data-lang-btn]');
    for (var j = 0; j < btns.length; j++) {
      btns[j].classList.toggle('active', btns[j].getAttribute('data-lang-btn') === lang);
    }

    try { localStorage.setItem(STORAGE_KEY, lang); } catch (e) { /* ignore */ }
  }

